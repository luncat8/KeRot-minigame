'use strict';

const fs = require('fs');
const path = require('path');
const ROOT = path.resolve(__dirname, '..');
const OUTPUT = path.join(ROOT, 'games', 'kerot.js');
const SOURCES = [
	'js/cfg.js',
	'js/field.js',
	'js/physics.js',
	'js/score.js',
	'js/players.js',
	'js/rules.js',
	'js/predict.js',
	'js/bots.js',
	'js/vote.js',
	'js/game.js',
	'js/render.js',
	'minigame/entry.js'
];

function indent(source) {
	return source.split('\n').map(line => '\t\t\t' + line).join('\n');
}

function moduleFactory(id, source) {
	return '\t\t' + JSON.stringify(id) + ': function(module, exports, require, globalThis) {\n'
		+ '\t\t\twith (globalThis) {\n' + indent(source) + '\n\t\t\t}\n\t\t}';
}

function build() {
	const factories = SOURCES.map(id => {
		const source = fs.readFileSync(path.join(ROOT, id), 'utf8').replace(/\s+$/, '');
		return moduleFactory(id, source);
	});
	const css = fs.readFileSync(path.join(ROOT, 'minigame/kerot.css'), 'utf8');
	factories.push(moduleFactory('minigame/style.js', 'module.exports = ' + JSON.stringify(css) + ';'));
	return '/* Generated by node tools/build-minigame.js. Do not edit.\n'
		+ '   Source: js/ plus minigame/entry.js and minigame/kerot.css.\n'
		+ '   Standalone classic script; no network, build runtime, or third-party libraries. */\n'
		+ '(function(host) {\n'
		+ '\tconst registry = host && host.SnowfallGames;\n'
		+ '\tif (!registry || typeof registry.add !== \'function\') {\n'
		+ '\t\tif (typeof console !== \'undefined\' && console.error) console.error(\'games/kerot.js requires snowfall-games.js first\');\n'
		+ '\t\tif (typeof module !== \'undefined\' && module.exports) module.exports = null;\n'
		+ '\t\treturn;\n'
		+ '\t}\n'
		+ '\t// The with-scope keeps the legacy classic-script names private to this bundle.\n'
		+ '\tconst scope = { SnowfallGames: registry };\n'
		+ '\tscope.globalThis = scope;\n'
		+ '\tconst factories = {\n' + factories.join(',\n') + '\n\t};\n'
		+ '\tconst cache = Object.create(null);\n'
		+ '\tfunction resolve(from, request) {\n'
		+ '\t\tif (request.charAt(0) !== \'.\') throw new Error(\'KeRot bundle only resolves relative modules: \' + request);\n'
		+ '\t\tconst parts = from.split(\'/\');\n'
		+ '\t\tparts.pop();\n'
		+ '\t\tfor (const part of request.split(\'/\')) {\n'
		+ '\t\t\tif (!part || part === \'.\') continue;\n'
		+ '\t\t\tif (part === \'..\') parts.pop();\n'
		+ '\t\t\telse parts.push(part);\n'
		+ '\t\t}\n'
		+ '\t\tconst id = parts.join(\'/\');\n'
		+ '\t\treturn /\\.js$/.test(id) ? id : id + \'.js\';\n'
		+ '\t}\n'
		+ '\tfunction load(id) {\n'
		+ '\t\tif (cache[id]) return cache[id].exports;\n'
		+ '\t\tconst factory = factories[id];\n'
		+ '\t\tif (!factory) throw new Error(\'KeRot bundle module not found: \' + id);\n'
		+ '\t\tconst mod = { exports: {} };\n'
		+ '\t\tcache[id] = mod;\n'
		+ '\t\tconst localRequire = request => load(resolve(id, request));\n'
		+ '\t\tfactory(mod, mod.exports, localRequire, scope);\n'
		+ '\t\treturn mod.exports;\n'
		+ '\t}\n'
		+ '\tconst spec = load(\'minigame/entry.js\');\n'
		+ '\tif (typeof module !== \'undefined\' && module.exports) module.exports = spec;\n'
		+ '})(typeof window !== \'undefined\' ? window : globalThis);\n';
}

const output = build();
if (process.argv.includes('--check')) {
	if (!fs.existsSync(OUTPUT) || fs.readFileSync(OUTPUT, 'utf8') !== output) {
		console.error('games/kerot.js is stale; run node tools/build-minigame.js');
		process.exit(1);
	}
	console.log('games/kerot.js matches its sources');
} else {
	fs.mkdirSync(path.dirname(OUTPUT), { recursive: true });
	fs.writeFileSync(OUTPUT, output);
	console.log('built games/kerot.js (' + Buffer.byteLength(output) + ' bytes)');
}
